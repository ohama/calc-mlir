module Program

open System.Reflection
open Argu
open FSharp.Text.Lexing
open Ast

[<HelpFlags("--help", "-h")>]
type CliArgs =
    | [<AltCommandLine("-e"); EqualsAssignmentOrSpaced>] Expr of expr: string
    | [<AltCommandLine("-v")>] Version
    | No_Typecheck
    | Emit_Mlir
    | [<EqualsAssignmentOrSpaced>] Compile of path: string
    | Keep_Temps
    | Repl
    | [<MainCommand; Last>] File of path: string
    interface IArgParserTemplate with
        member a.Usage =
            match a with
            | Expr _ -> "evaluate the given expression (reads stdin if omitted)"
            | Version -> "print version and exit"
            | No_Typecheck -> "skip static type inference (types are still checked while evaluating)"
            | Emit_Mlir -> "print the MLIR generated by the compiler instead of evaluating"
            | Compile _ -> "compile to a native executable at the given path instead of evaluating"
            | Keep_Temps -> "with --compile, keep the intermediate .mlir, .ll and .o files"
            | Repl -> "start the interactive REPL (also the default when no file or --expr is given and stdin is a terminal)"
            | File _ -> "run a program file: prints only what the program prints, then the result unless it is ()"

let parse = Frontend.parse
let version = Frontend.version
let runWithLargeStack f = Frontend.runWithLargeStack f
let errorLocation = Frontend.errorLocation

/// 빠진 분기 경고: 표준 에러로, 오류와 같은 위치 표시. 실행은 계속함 (OCaml, F# 와 같음)
let printWarnings (input: string) (warnings: Infer.Warning list) =
    for w in warnings do
        match w.Position with
        | Some (line, column) ->
            eprintfn "Warning: %s (line %d, column %d)" w.Message line column
            errorLocation input line column |> List.iter (eprintfn "%s")
        | None -> eprintfn "Warning: %s" w.Message

/// 타입 검사: 경고를 출력하고 타입을 돌려줌. 추론도 식의 깊이만큼 재귀하므로 평가와 같은 큰 스택에서 실행
let typecheckAndWarn (input: string) (ast: Ast.Expr) =
    let t, warnings = runWithLargeStack (fun () -> Infer.typecheckWithWarnings ast)
    printWarnings input warnings
    t

let run (typecheck: bool) (input: string) =
    try
        let ast = parse input
        printfn "AST:    %A" ast
        if typecheck then
            printfn "Type:   %s" (Infer.typeToString (typecheckAndWarn input ast))
        let value = runWithLargeStack (fun () -> Eval.eval ast)
        printfn "Result: %s" (Eval.formatValue value)
        0
    with
    | Errors.SyntaxError (_, line, column) as ex ->
        eprintfn "Error: %s" ex.Message
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | Infer.TypeError (message, Some (line, column)) ->
        eprintfn "Error: %s (line %d, column %d)" message line column
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | ex ->
        eprintfn "Error: %s" ex.Message
        1

type CompileMode =
    | EmitMlir
    | BuildExecutable of path: string * keepTemps: bool

/// 타입 추론을 통과한 프로그램만 컴파일 (docs/compiler-design.md 1장)
let compile (mode: CompileMode) (input: string) =
    try
        let ast = parse input
        typecheckAndWarn input ast |> ignore
        let mlir = Codegen.emitProgram ast
        match mode with
        | EmitMlir ->
            printf "%s" mlir
            0
        | BuildExecutable (path, keepTemps) ->
            match Toolchain.find () with
            | Error message ->
                eprintfn "Error: %s" message
                1
            | Ok tools ->
                match Toolchain.build tools mlir path keepTemps with
                | Some dir -> eprintfn "Intermediate files: %s" dir
                | None -> ()
                0
    with
    | Errors.SyntaxError (_, line, column) as ex ->
        eprintfn "Error: %s" ex.Message
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | Infer.TypeError (message, Some (line, column)) ->
        eprintfn "Error: %s (line %d, column %d)" message line column
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | ex ->
        eprintfn "Error: %s" ex.Message
        1

/// 프로그램 파일 실행 (calc prog.calc): OCaml, dotnet fsi 처럼 프로그램의 출력만 보여 주고, 마지막 값이 () 가 아니면 그 값을 출력
let runFile (typecheck: bool) (input: string) =
    try
        let ast = parse input
        if typecheck then typecheckAndWarn input ast |> ignore
        let value = runWithLargeStack (fun () -> Eval.eval ast)
        match value with
        | Eval.VUnit -> ()
        | v -> printfn "%s" (Eval.formatValue v)
        0
    with
    | Errors.SyntaxError (_, line, column) as ex ->
        stdout.Flush()
        eprintfn "Error: %s" ex.Message
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | Infer.TypeError (message, Some (line, column)) ->
        eprintfn "Error: %s (line %d, column %d)" message line column
        errorLocation input line column |> List.iter (eprintfn "%s")
        1
    | ex ->
        stdout.Flush()
        eprintfn "Error: %s" ex.Message
        1

[<EntryPoint>]
let main argv =
    let parser = ArgumentParser.Create<CliArgs>(programName = "calc")
    try
        let results = parser.ParseCommandLine(argv)
        if results.Contains Version then
            printfn "calc %s" (version ())
            0
        else
            let typecheck = not (results.Contains No_Typecheck)
            let file = results.TryGetResult File
            let input () =
                match results.TryGetResult Expr, file with
                | Some expr, _ -> expr
                | None, Some path -> System.IO.File.ReadAllText path
                | None, None -> stdin.ReadToEnd()
            let mode =
                match results.TryGetResult Compile with
                | Some path -> Some (BuildExecutable (path, results.Contains Keep_Temps))
                | None when results.Contains Emit_Mlir -> Some EmitMlir
                | None -> None
            match mode with
            | Some _ when not typecheck ->
                eprintfn "Error: --compile and --emit-mlir require type checking (remove --no-typecheck)"
                1
            | Some mode -> compile mode (input ())
            | None when file.IsSome && not (results.Contains Expr) -> runFile typecheck (input ())
            | None when results.Contains Repl || (not (results.Contains Expr) && file.IsNone && not System.Console.IsInputRedirected) ->
                Repl.run
                    (sprintf "calc %s REPL. End each input with ;;  Exit with #quit;; or Ctrl-D." (version ()))
                    stdin
                    stdout
                0
            | None -> run typecheck (input ())
    with :? ArguParseException as ex ->
        match ex.ErrorCode with
        | ErrorCode.HelpText ->
            printfn "%s" ex.Message
            0
        | _ ->
            eprintfn "%s" ex.Message
            1
